#!/usr/bin/env python3
"""Generate contracts/decision_cases.json from the Python implementation (the reference).

Both SDKs replay it: the Node tests must reach exactly the same decision for every case.
Re-run after any change to the decision rules and commit the result with the change.
"""

import json
import os
import sys
from datetime import datetime, timedelta, timezone

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
from yisuite_access.decision import Person, WorkspaceAccess, decide
from yisuite_access.table_model import EXAMPLE

NOW = datetime(2026, 10, 27, tzinfo=timezone.utc)
iso = lambda d: d.isoformat().replace('+00:00', 'Z') if d else None


def person(**kw):
    base = dict(user_id=1, org_id=5, org_type='client', org_role='owner', plan_key='standard', plan_status='active')
    base.update(kw)
    return base


PEOPLE = {
    'owner live': person(),
    'owner trialing': person(plan_status='trialing'),
    'owner past due': person(plan_status='past_due'),
    'owner starter': person(plan_key='starter'),
    'owner premium': person(plan_key='premium'),
    'owner lapsed 10d': person(plan_status='expired', plan_lapsed_since=NOW - timedelta(days=10)),
    'owner lapsed 40d': person(plan_status='expired', plan_lapsed_since=NOW - timedelta(days=40)),
    'owner lapsed unknown date': person(plan_status='canceled'),
    'member': person(org_role='member'),
    'no org': person(org_id=None, org_type=None, org_role=None, plan_key=None, plan_status=None),
    'no plan': person(plan_key=None, plan_status=None),
    'unknown plan': person(plan_key='platinum'),
    'unknown status': person(plan_status='frozen'),
    # Eve's resolved entitlement (`ent`): the plan key is ignored when it is present.
    'owner ent core': person(plan_key='platinum', ent={'b': ['core'], 'add': [], 'rm': [], 'lim': {}, 'st': 'live'}),
    'owner ent banking+ai': person(ent={'b': ['core', 'banking', 'ai'], 'add': [], 'rm': [], 'lim': {}, 'st': 'live'}),
    'owner ent added ai key': person(ent={'b': ['core'], 'add': ['ai.assistant'], 'rm': [], 'lim': {}, 'st': 'live'}),
    'owner ent removed list key': person(ent={'b': ['core'], 'add': [], 'rm': ['tickets.list'], 'lim': {}, 'st': 'live'}),
    'owner ent read only': person(ent={'b': ['core', 'banking'], 'add': [], 'rm': [], 'lim': {}, 'st': 'read_only'}),
    'owner ent locked': person(ent={'b': ['core', 'banking'], 'add': [], 'rm': [], 'lim': {}, 'st': 'locked'}),
    'owner ent unknown state': person(ent={'b': ['core'], 'add': [], 'rm': [], 'lim': {}, 'st': 'frozen'}),
    'member ent banking': person(org_role='member', ent={'b': ['core', 'banking'], 'add': [], 'rm': [], 'lim': {}, 'st': 'live'}),
    'platform admin': dict(user_id=9, platform_role='platform-admin'),
    'platform support': dict(user_id=8, platform_role='support'),
}
WORKSPACES = {
    'owner ws': dict(key='w', level='owner', status='ready'),
    'editor ws': dict(key='w', level='editor', status='ready'),
    'viewer ws': dict(key='w', level='viewer', status='ready'),
    'suspended ws': dict(key='w', level='owner', status='suspended'),
    'archived ws': dict(key='w', level='owner', status='archived'),
    'accountant role ws': dict(key='w', level='editor', status='ready', app_role='Accountant'),
    'member role ws': dict(key='w', level='editor', status='ready', app_role='Member'),
    'none': None,
}
REQUESTS = [
    ('read ticket', ['tickets.list'], 'GET', '/t'),
    ('write ticket', ['tickets.create'], 'POST', '/t'),
    ('banking', ['banking.import'], 'GET', '/b'),
    ('ai', ['ai.assistant'], 'GET', '/a'),
    ('either key', ['ai.assistant', 'tickets.list'], 'GET', '/t'),
    ('admin key', ['admin.tenants'], 'GET', '/x'),
    ('report post', ['tickets.list'], 'POST', '/reports/run'),
    ('export', ['tickets.list'], 'GET', '/t/export'),
    ('mystery key', ['mystery.key'], 'GET', '/m'),
]


def build_person(d):
    if d is None:
        return None
    d = dict(d)
    return Person(**d)


cases = []
for pn, pd in list(PEOPLE.items()) + [('anonymous', None)]:
    for wn, wd in WORKSPACES.items():
        for rn, keys, method, path in REQUESTS:
            ws = WorkspaceAccess(**wd) if wd else None
            d = decide(build_person(pd), ws, keys, method, path, EXAMPLE, now=NOW)
            cases.append({
                'name': f'{pn} | {wn} | {rn}',
                'person': ({**pd, 'plan_lapsed_since': iso(pd.get('plan_lapsed_since'))} if pd else None),
                'workspace': wd, 'keys': keys, 'method': method, 'path': path, 'now': iso(NOW),
                'expect': {'allowed': d.allowed, 'code': d.code, 'status': d.refusal.status if d.refusal else None,
                           'role': d.role, 'level': d.level}})

out = {'_comment': 'Generated by python/scripts/gen_decision_cases.py from the reference implementation.',
       'model': EXAMPLE.to_dict(), 'cases': cases}
path = os.path.join(os.path.dirname(__file__), '..', '..', 'contracts', 'decision_cases.json')
json.dump(out, open(path, 'w'), indent=1, sort_keys=True)
print(f'{len(cases)} cases -> {os.path.normpath(path)}')
